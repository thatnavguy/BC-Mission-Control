// Generates src/webAssets.generated.js from web/dist so the single-executable
// build can serve the UI from memory. Run after `npm --prefix web run build`.
const fs = require('fs');
const path = require('path');

const dist = path.resolve(__dirname, '..', '..', 'web', 'dist');
const out = path.resolve(__dirname, '..', 'src', 'webAssets.generated.js');

const MIME = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.map': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.txt': 'text/plain',
  '.webmanifest': 'application/manifest+json'
};

if (!fs.existsSync(path.join(dist, 'index.html'))) {
  console.error('web/dist not found — run `npm --prefix web run build` first.');
  process.exit(1);
}

const files = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(dist);

let src = '// Generated by scripts/embed-web.js — do not edit.\nmodule.exports = {\n';
for (const file of files) {
  const rel = path.relative(dist, file).split(path.sep).join('/');
  const type = MIME[path.extname(file).toLowerCase()] || 'application/octet-stream';
  const data = fs.readFileSync(file).toString('base64');
  src += `${JSON.stringify(rel)}:{type:${JSON.stringify(type)},data:${JSON.stringify(data)}},\n`;
}
src += '};\n';

fs.writeFileSync(out, src);
console.log(`Embedded ${files.length} file(s) from web/dist (${(src.length / 1024).toFixed(0)} KB generated)`);
